import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { buildPreview } from '../../../../manual/build/index.mjs';

const root = path.resolve(import.meta.dirname, '../../../..');

test('sole orchestrator builds deterministic semantic HTML and pseudolocale in preview mode', async () => {
  const parent = await fs.mkdtemp(path.join(os.tmpdir(), 'aperio-manual-test-'));
  const output = path.join(parent, 'packet');
  try {
    const { report } = await buildPreview(root, { outputRoot: output, htmlOnly: true });
    assert.equal(report.identity, 'NON-RELEASE');
    assert.equal(report.releaseEligible, false);
    assert.deepEqual(report.phases, ['resolve', 'acquire', 'preflight', 'generate', 'assemble', 'html', 'atomic-promote']);
    const html = await fs.readFile(path.join(output, 'aperio-manual-part-i-NON-RELEASE.html'), 'utf8');
    const pseudo = await fs.readFile(path.join(output, 'evidence/internal/pseudolocale/aperio-manual-part-i-pseudolocale-NON-RELEASE.html'), 'utf8');
    assert.match(html, /<html lang="en"/);
    assert.match(pseudo, /<html lang="en-x-pseudo"/);
    assert.doesNotMatch(html, /<strong[\s>]/);
    assert.match(html, /Seven parts \/ 26 planned canonical chapters/);
    assert.match(html, /class="manual-page night cover"/);
    assert.match(html, /class="manual-page night part-opener"/);
    assert.match(html, /class="manual-page signal-desk procedure"/);
    assert.match(html, /class="manual-page field-console/);
    assert.equal(report.treatment.source, 'manual/styles/visual-system.mjs');
    assert.equal(report.treatment.integrationAuthorized, true);
    assert.match(html, /data:image\/png;base64/);
    assert.match(html, /data:image\/webp;base64/);
    assert.match(html, /data:image\/svg\+xml;base64/);
    assert.match(html, /platform-lanes/);
    assert.match(html, /signal-flow/);
    assert.match(html, /<svg class="signal-return"[^>]+aria-hidden="true"/);
    assert.doesNotMatch(html, /mask-composite/);
    assert.match(html, /Chapters 3–4 are the current editorial checkpoint/);
    assert.doesNotMatch(html, /complete authored draft|All 26 chapters in this review checkpoint are genuinely authored/);
    assert.match(html, /id="chapter\.memory-knowledge"/);
    assert.match(html, /id="procedure\.maintain-memory"/);
    assert.match(html, /id="procedure\.synthesize-wiki-article"/);
    assert.match(html, /id="example\.correct-coffee-grinder-setting"/);
    assert.match(html, /Expected observable result/);
    assert.match(html, /No wiki articles matched &quot;garden sensor handoff&quot;\./);
    assert.match(html, /id="chapter\.conversations-sessions-agents"/);
    assert.match(html, /id="example\.branch-garden-budget"/);
    assert.match(html, /id="procedure\.inspect-inactive-agent-job"/);
    assert.match(html, /Definition, trigger, run, interrupt, result, and cleanup are separate states/);
    assert.match(html, /id="chapter\.tools-files-artifacts"/);
    assert.match(html, /id="chapter\.code-document-knowledge"/);
    assert.match(html, /id="chapter\.connect-agent-client"/);
    assert.match(html, /id="chapter\.integrations-external-data"/);
    assert.match(html, /id="chapter\.agents-automation"/);
    assert.match(html, /id="chapter\.install-deploy"/);
    assert.match(html, /id="chapter\.configure"/);
    assert.match(html, /id="chapter\.storage-health"/);
    assert.match(html, /id="chapter\.privacy-security"/);
    assert.match(html, /id="chapter\.lifecycle"/);
    assert.match(html, /id="chapter\.contributor-workstation"/);
    assert.match(html, /id="chapter\.change-safely"/);
    assert.match(html, /id="chapter\.verify-release"/);
    assert.match(html, /id="chapter\.troubleshoot"/);
    assert.match(html, /id="chapter\.evidence-escalate"/);
    assert.match(html, /id="chapter\.release-support"/);
    assert.match(html, /id="chapter\.configuration-catalog"/);
    assert.match(html, /id="chapter\.commands-checks"/);
    assert.match(html, /id="chapter\.capability-catalog"/);
    assert.match(html, /id="chapter\.data-portability"/);
    assert.match(html, /id="chapter\.glossary"/);
    assert.match(html, /id="chapter\.index"/);
    assert.match(html, /id="term\.portable-export"/);
    assert.match(html, /Alternate terms route to one definition/);
    assert.match(html, /id="full-index-entries"/);
    assert.match(html, /<th scope="col">A4<\/th><th scope="col">Letter<\/th>/);
    assert.doesNotMatch(html, /data-target=/);
    assert.match(html, /id="backmatter\.license"/);
    assert.match(html, /id="backmatter\.acknowledgments"/);
    assert.match(html, /id="backmatter\.support-links"/);
    assert.match(html, /Pinned v0\.68\.0 changelog/);
    assert.match(html, /class="manual-page field-console\s*" id="symptom\.startup-fails"/);
    assert.doesNotMatch(html, /content remains owned by C03-C11/i);
    assert.doesNotMatch(html, /Placeholder only|Later chapters 3-14|Later chapters 15-26/i);
    assert.doesNotMatch(html, /href="(?!#)[^"]*pseudolocale/i);
  } finally {
    await fs.rm(parent, { recursive: true, force: true });
  }
});
