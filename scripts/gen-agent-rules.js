// scripts/gen-agent-rules.js
//
// Fans one canonical ruleset out to per-platform adapters, so an agent on any
// host learns Aperio's memory discipline and no copy can drift from the source:
//
//   id/agent-rules/aperio-memory.md          the canonical doctrine (hand-written)
//     → integrations/agent-rules/
//         AGENTS.snippet.md                  paste-into-AGENTS.md block
//         cursor/aperio-memory.mdc           Cursor rule, with its frontmatter
//         claude-code/aperio-memory/SKILL.md Claude Code skill, house frontmatter
//
//   node scripts/gen-agent-rules.js                → write every adapter
//   node scripts/gen-agent-rules.js --check        → exit 1 if any is stale (CI)
//   node scripts/gen-agent-rules.js --out-dir DIR  → write into DIR (tests)
//
// The adapters are generated artifacts: never hand-edit one. Change the
// canonical file and re-run. The distribution pattern (one ruleset, mechanical
// per-platform copies, a check script that fails the build on drift) is
// borrowed from DietrichGebert/ponytail, MIT.

import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, resolve, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const CANON_REL = "id/agent-rules/aperio-memory.md";
const CANON = join(ROOT, ...CANON_REL.split("/"));

const outDirIdx = process.argv.indexOf("--out-dir");
const OUT_DIR = outDirIdx !== -1
  ? resolve(process.argv[outDirIdx + 1])
  : join(ROOT, "integrations", "agent-rules");

// ── canonical source ──────────────────────────────────────────────────────────
// A three-key frontmatter (name / description / keywords) feeds each adapter's
// own header, so platform metadata is derived rather than restated. Parsed by
// hand: the shape is fixed and known, and a YAML dependency would be a new
// runtime dep for six lines of text.
function parseCanonical(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${CANON_REL} must open with a frontmatter block.`);
  const [, fm, body] = m;

  const scalar = (key) => {
    // `key: value` or a folded `key: >` block whose indented lines follow.
    // The inline form must start on a non-`>` character — anchoring with a bare
    // lookahead lets the whitespace class backtrack and swallow the fold marker.
    const inline = fm.match(new RegExp(`^${key}:[ \\t]+([^>\\s].*)$`, "m"));
    if (inline) return inline[1].trim().replace(/^["']|["']$/g, "");
    // Folded block: the marker line, then every following indented line. Matched
    // as an explicit run of indented lines — a lazy `[\s\S]*?` with a `$`
    // lookahead stops at the first newline, because `m` makes `$` line-anchored.
    const folded = fm.match(new RegExp(`^${key}:[ \\t]*>[ \\t]*((?:\\n[ \\t]+.*)+)`, "m"));
    if (folded) return folded[1].split("\n").map((l) => l.trim()).filter(Boolean).join(" ");
    throw new Error(`${CANON_REL} frontmatter is missing \`${key}\`.`);
  };

  return { name: scalar("name"), description: scalar("description"), keywords: scalar("keywords"), body: body.trim() };
}

// ── shared banner ─────────────────────────────────────────────────────────────
// Every adapter says what it is, where it came from, and how to regenerate it,
// plus the ponytail attribution the pattern is borrowed under.
const banner = (comment = true) => {
  const lines = [
    "AUTO-GENERATED — do not edit this file.",
    `Source: ${CANON_REL} · regenerate with \`npm run gen:agent-rules\`.`,
    "Distribution pattern adapted from DietrichGebert/ponytail (MIT).",
  ];
  return comment ? `<!--\n${lines.map((l) => `  ${l}`).join("\n")}\n-->` : lines.map((l) => `> ${l}`).join("\n");
};

// ── adapters ──────────────────────────────────────────────────────────────────
function buildAgentsSnippet(c) {
  // Pasted into an existing AGENTS.md / CLAUDE.md, so it must carry no
  // frontmatter of its own and must start at a heading level that nests.
  return [
    banner(),
    "",
    c.body,
    "",
  ].join("\n");
}

function buildCursorRule(c) {
  return [
    "---",
    `description: ${c.description}`,
    "globs:",
    "alwaysApply: false",
    "---",
    "",
    banner(),
    "",
    c.body,
    "",
  ].join("\n");
}

function buildClaudeCodeSkill(c) {
  return [
    "---",
    `name: ${c.name}`,
    "description: >",
    ...wrap(c.description, 76).map((l) => `  ${l}`),
    "metadata:",
    `  keywords: "${c.keywords}"`,
    '  category: "memory"',
    '  load: "on-demand"',
    "---",
    "",
    banner(),
    "",
    c.body,
    "",
  ].join("\n");
}

function wrap(text, width) {
  const out = [];
  let line = "";
  for (const word of text.split(/\s+/)) {
    if (line && (line + " " + word).length > width) { out.push(line); line = word; }
    else line = line ? `${line} ${word}` : word;
  }
  if (line) out.push(line);
  return out;
}

// ── entry point ───────────────────────────────────────────────────────────────
const canonical = parseCanonical(readFileSync(CANON, "utf8"));

const outputs = [
  { rel: "AGENTS.snippet.md", content: buildAgentsSnippet(canonical) },
  { rel: join("cursor", "aperio-memory.mdc"), content: buildCursorRule(canonical) },
  { rel: join("claude-code", "aperio-memory", "SKILL.md"), content: buildClaudeCodeSkill(canonical) },
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const o of outputs) {
    let current = "";
    try { current = readFileSync(join(OUT_DIR, o.rel), "utf8"); } catch { /* missing → out of date */ }
    if (current !== o.content) {
      console.error(`✗ ${o.rel} is out of date. Run \`npm run gen:agent-rules\`.`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(`✓ agent-rules adapters are up to date (${outputs.length} files).`);
} else {
  for (const o of outputs) {
    const path = join(OUT_DIR, o.rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, o.content);
  }
  console.log(`✓ Wrote ${outputs.length} agent-rules adapters from ${CANON_REL}.`);
}
